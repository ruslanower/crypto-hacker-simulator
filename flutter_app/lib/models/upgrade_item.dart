import 'package:flutter/material.dart';

enum UpgradeType {
  hardware, // Boosts manual click / mining power
  software, // Passive automated income (CPS)
  cooling,  // Reduces hardware temperature & prevents throttling
  security, // Lowers heat generation or cleans active heat
}

class UpgradeItem {
  final String id;
  final String name;
  final String description;
  final UpgradeType type;
  final double baseCost;
  final double costMultiplier;
  final double basePower; // CPS or Tap power or Heat reduction
  final IconData icon;
  final int levelRequired;
  int count;

  UpgradeItem({
    required this.id,
    required this.name,
    required this.description,
    required this.type,
    required this.baseCost,
    this.costMultiplier = 1.15,
    required this.basePower,
    required this.icon,
    this.levelRequired = 1,
    this.count = 0,
  });

  /// Cost for the next unit: BaseCost * (Multiplier ^ count)
  double get currentCost {
    double cost = baseCost;
    for (int i = 0; i < count; i++) {
      cost *= costMultiplier;
    }
    return cost;
  }

  /// Total power generated by all owned units of this item
  double get totalPower => count * basePower;

  Map<String, dynamic> toJson() => {
    'id': id,
    'count': count,
  };

  void loadFromJson(Map<String, dynamic> json) {
    count = json['count'] as int? ?? 0;
  }

  UpgradeItem copyWith({int? count}) {
    return UpgradeItem(
      id: id,
      name: name,
      description: description,
      type: type,
      baseCost: baseCost,
      costMultiplier: costMultiplier,
      basePower: basePower,
      icon: icon,
      levelRequired: levelRequired,
      count: count ?? this.count,
    );
  }
}
